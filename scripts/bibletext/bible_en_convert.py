import argparse
import collections
import os
import re

ORDER = ('GEN EXO LEV NUM DEU JOS JDG RUT 1SA 2SA 1KI 2KI 1CH 2CH EZR NEH EST JOB PSA PRO ECC SNG ISA JER LAM EZK DAN HOS JOL AMO OBA JON MIC NAM HAB ZEP HAG ZEC MAL '
         'MAT MRK LUK JHN ACT ROM 1CO 2CO GAL EPH PHP COL 1TH 2TH 1TI 2TI TIT PHM HEB JAS 1PE 2PE 1JN 2JN 3JN JUD REV').split()
# KJV 원본 파일 이름(확장자 제외)
KJV_FILE = dict(zip(ORDER, ['Genesis', 'Exodus', 'Leviticus', 'Numbers', 'Deuteronomy', 'Joshua', 'Judges', 'Ruth', '1 Samuel', '2 Samuel', '1 Kings', '2 Kings',
 '1 Chronicles', '2 Chronicles', 'Ezra', 'Nehemiah', 'Esther', 'Job', 'Psalms', 'Proverbs', 'Ecclesiastes', 'SongofSolomon', 'Isaiah', 'Jeremiah', 'Lamentations',
 'Ezekiel', 'Daniel', 'Hosea', 'Joel', 'Amos', 'Obadiah', 'Jonah', 'Micah', 'Nahum', 'Habakkuk', 'Zephaniah', 'Haggai', 'Zechariah', 'Malachi', 'Matthew', 'Mark', 'Luke',
 'John', 'Acts', 'Romans', '1 Corinthians', '2 Corinthians', 'Galatians', 'Ephesians', 'Philippians', 'Colossians', '1 Thessalonians', '2 Thessalonians', '1 Timothy',
 '2 Timothy', 'Titus', 'Philemon', 'Hebrews', 'James', '1 Peter', '2 Peter', '1 John', '2 John', '3 John', 'Jude', 'Revelation']))


def tidy(s):
    """공백 묶음을 공백 하나로 줄이고 양끝을 자른다."""
    return re.sub(r'\s+', ' ', s).strip()


def kjv(kjv_dir):
    """KJV .txt 66권을 중간 형식 {USFM 코드: {"name", "chapters": {장: [{"v", "heading", "text"}]}}} 으로 읽는다."""
    out = {}
    for code in ORDER:
        name = KJV_FILE[code]
        chapters = collections.OrderedDict(); cur = None; pending = []; last = None
        for raw in open(os.path.join(kjv_dir, f'{name}.txt'), encoding='utf-8').read().replace('\f', '\n').split('\n'):
            line = raw.strip()
            if not line or line.startswith('PAGE'): continue
            m = re.match(r'^(?:CHAPTER|PSALM)\s+(\d+)$', line)
            if m: cur = m.group(1); chapters[cur] = []; pending = []; last = None; continue
            if cur is None: continue                                    # 책 제목 · 서문
            m = re.match(r'^(\d+)\s+(.*)$', line)
            if m and not (m.group(2).isupper() and last is not None and int(m.group(1)) != last + 1):
                v, text = int(m.group(1)), m.group(2)
                # 줄 안에 붙은 다음 절(빌레몬서 1:2)
                parts = re.split(r'\s(?=%d\s+[A-Z¶])' % (v + 1), text, maxsplit=1)
                for i, part in enumerate(parts):
                    part = re.sub(r'^%d\s+' % (v + i), '', part) if i else part
                    chapters[cur].append({'v': v + i, 'heading': pending, 'text': tidy(part.replace('¶', ''))}); pending = []
                last = v + len(parts) - 1; continue
            if line.startswith('¶'): continue                           # 서신 끝 맺음말
            if code == 'PSA' and re.match(r'^[A-Z]+\.$', line): pending.append(line.rstrip('.').title()); continue   # 119편 자모(ALEPH.)
            if line.isupper() and len(line.split()) <= 4: continue      # 책 이름 꼬리말
            pending.append(tidy(line.rstrip('.')).title() if code == 'PSA' and line.isupper() else tidy(line))  # 시편 표제
        out[code] = {'name': name.replace('SongofSolomon', 'Song of Solomon'), 'chapters': chapters}
    return out


def bsb(bsb_dir):
    """BSB .usfm 66권을 KJV 와 같은 중간 형식으로 읽는다."""
    out = {}
    for code in ORDER:
        src = open(os.path.join(bsb_dir, f'{code}.usfm'), encoding='utf-8').read()
        name = re.search(r'^\\h (.+)$', src, re.M).group(1).strip()
        src = re.sub(r'\\f .*?\\f\*', '', src, flags=re.S)              # 각주
        src = re.sub(r'\\x .*?\\x\*', '', src, flags=re.S)              # 교차 참조(있다면)
        chapters = collections.OrderedDict(); cur = None; pending = []; verse = None

        def flush():
            nonlocal verse
            if verse is not None:
                verse['text'] = tidy(verse['text']); chapters[cur].append(verse); verse = None
        for raw in src.split('\n'):
            line = raw.rstrip()
            m = re.match(r'^\\(\w+)\s?(.*)$', line)
            if not m:
                if verse is not None: verse['text'] += ' ' + line
                continue
            tag, rest = m.group(1), m.group(2)
            if tag == 'ms': flush(); pending.append('Book ' + tidy(rest).split()[-1]); continue
            if tag in ('id', 'usfm', 'h', 'toc1', 'toc2', 'toc3', 'mt1', 'mt2', 'r', 'mr', 'b'): continue
            if tag == 'c': flush(); cur = rest.strip(); chapters[cur] = []; pending = []; continue
            if tag in ('s1', 's2', 'qa'):
                flush(); t = tidy(rest)
                if t and tag != 'qa' or (tag == 'qa' and not re.match(r'^[\u0590-\u05FF]+$', t)): pending.append(t.title() if tag == 'qa' else t)
                continue
            if tag == 'd':                                              # 시편 표제: "\d \v 1 제목" 또는 "\d 제목"
                mv = re.match(r'^\\v (\d+)\s+(.*)$', rest)
                if mv:
                    flush(); pending.append(tidy(mv.group(2))); verse = {'v': int(mv.group(1)), 'heading': pending, 'text': ''}; pending = []
                elif not (pending and pending[-1].startswith('Book ')): pending.append(tidy(rest))   # 권 표시 뒤 범위(Psalms 1–41)는 뺀다
                continue
            # 단락 · 시 · 들여쓰기 표지: 내용만 이어 붙이고 줄 안의 \v 로 절을 나눈다
            body = re.sub(r'\\wj\*?|\\pc|\\qr', '', rest)
            for piece in re.split(r'(\\v \d+\s)', body):
                mv = re.match(r'^\\v (\d+)\s$', piece)
                if mv:
                    flush(); verse = {'v': int(mv.group(1)), 'heading': pending, 'text': ''}; pending = []
                elif verse is not None: verse['text'] += ' ' + piece
        flush()
        out[code] = {'name': name, 'chapters': chapters}
    return out


def check(label, data):
    """절 순서 · 중복 · 빈 본문 · 표지 찌꺼기를 검사해 요약을 찍고 문제 수를 돌려준다."""
    total = sum(len(vs) for b in data.values() for vs in b['chapters'].values())
    probs = []
    for code, b in data.items():
        for c, vs in b['chapters'].items():
            nums = [x['v'] for x in vs]
            if nums != sorted(set(nums)): probs.append((code, c, 'order/dup'))
            for x in vs:
                if not x['text']: probs.append((code, c, x['v'], 'empty'))
                if re.search(r'\\|PAGE|MERGEFORMAT', x['text']): probs.append((code, c, x['v'], 'residue', x['text'][:40]))
    print(f'{label}: 책 {len(data)} · 장 {sum(len(b["chapters"]) for b in data.values())} · 절 {total} · 문제 {len(probs)}', probs[:8])
    return len(probs)


def emit(data, label, out_dir, nkrv_dir):
    """`<out_dir>/<label>/<label>-<개역개정 파일 이름>` 으로 앱 본문 형식을 쓴다(줄 구분 CR, 파일 끝 CR 없음, UTF-8)."""
    nkrv = sorted(f for f in os.listdir(nkrv_dir) if f.endswith('.txt'))
    assert len(nkrv) == 66, f'개역개정 폴더의 .txt 가 66개가 아니다: {len(nkrv)}'
    os.makedirs(os.path.join(out_dir, label), exist_ok=True)
    for code, raw in zip(ORDER, nkrv):
        lines = []
        for c, vs in data[code]['chapters'].items():
            for x in vs:
                head = '<' + '\n'.join(x['heading']) + '> ' if x['heading'] else ''
                lines.append(f"{c}:{x['v']} {head}{x['text']}")
        with open(os.path.join(out_dir, label, f'{label}-{raw}'), 'w', encoding='utf-8', newline='') as file:
            file.write('\r'.join(lines))
    return list(zip(ORDER, nkrv))


def main():
    parser = argparse.ArgumentParser(description='KJV(txt) · BSB(USFM) 를 앱 본문 리소스 형식으로 바꾼다.')
    parser.add_argument('--kjv', required=True, help='KJV .txt 폴더(christislord12/kjv-txt-files)')
    parser.add_argument('--bsb', required=True, help='BSB .usfm 폴더(bsb_usfm.zip 을 푼 것)')
    parser.add_argument('--nkrv', required=True, help='개역개정 본문 폴더 — 출력 파일 이름의 권 순서 · 이름을 여기서 가져온다')
    parser.add_argument('--out', required=True, help='출력 폴더 — 그 아래 KJV/ · BSB/ 에 쓴다')
    args = parser.parse_args()

    k, b = kjv(args.kjv), bsb(args.bsb)
    problems = check('KJV', k) + check('BSB', b)
    ks = {(c, ch, x['v']) for c, bk in k.items() for ch, vs in bk['chapters'].items() for x in vs}
    bs = {(c, ch, x['v']) for c, bk in b.items() for ch, vs in bk['chapters'].items() for x in vs}
    print('KJV 에만:', sorted(ks - bs)); print('BSB 에만:', sorted(bs - ks))
    pairs = []
    for label, data in (('KJV', k), ('BSB', b)):
        pairs = emit(data, label, args.out, args.nkrv)
    print('이름 짝 확인:', [p for p in pairs if p[0] in ('GEN', 'PSA', 'SNG', '1JN', '3JN', 'REV')])
    return 1 if problems else 0


if __name__ == '__main__':
    raise SystemExit(main())
